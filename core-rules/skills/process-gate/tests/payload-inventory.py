#!/usr/bin/env python3
"""Grep shell payloads for sourced/interpreted files missing from the manifest.

This is a conservative source-code inventory, not a shell interpreter. New
call spellings must be reviewed and mapped here, and every payload mapping must
also be present in the adapter's live preflight manifest. An inline literal
script (-c, or - fed by a quoted heredoc) is not a payload file, but one that
loads a file itself, or is passed a payload path, is checked like any call.
approval.py, generated by run-diff from a literal heredoc in its private work
directory, is not an external payload file.
"""

import pathlib
import re
import sys

adapter, diff, osv, engine, common, diff_base = map(pathlib.Path, sys.argv[1:])
text = adapter.read_text()
match = re.search(r"_pg_payload_manifest=\(\n(.*?)\n\)", text, re.S)
if not match:
    sys.exit("payload inventory: adapter manifest is missing")
manifest = set(re.findall(r"^\s*([a-z][a-z-]+)\s*$", match.group(1), re.M))

# Shell expressions at actual call sites -> entries of the one runtime list.
# These mappings intentionally fail closed on a new/unrecognized target.
payload = {
    "$_pg_engine": "security-engine",
    "$_pg_common": "process-common",
    "$_pg_gate": "gate",
    "$_pg_validator": "security-baseline",
    "$SKILL_DIR/scripts/lib/engine.sh": "security-engine",
    "$_sg_lib_dir/engine.sh": "security-engine",
    "$DIFF_BASE_LIB": "security-diff-base",
    "${BASH_SOURCE[0]%/*}/diff-base.sh": "process-common-diff-base",
    "$SKILL_DIR/scripts/lib/baseline_state.py": "security-baseline",
    "$SKILL_DIR/scripts/lib/osv.sh": "security-osv",
}
word = r"""(?:"[^"]*"|'[^']*'|[^\s;|&)]+)"""
# A command position: line start or a separator, then any reserved words,
# prefix builtins and assignments that can precede the command itself. An
# assignment value is whole words, so X="$(f "$BASH")" is not X=... $BASH.
assignment = r"""[A-Za-z_][A-Za-z0-9_]*=(?:"[^"]*"|'[^']*'|[^\s;|&)"'`])*"""
lead = (
    r"(?:^|[;|&(`]|\$\()[ \t]*"
    r"(?:(?:if|elif|while|until|then|else|do|time|command|builtin|exec|!|\{)[ \t]+"
    r"|" + assignment + r"[ \t]+)*"
)
source_call = re.compile(lead + r"(?:source|\.)[ \t]+(" + word + ")", re.M)
eval_call = re.compile(lead + r"eval\b", re.M)
shells = ("bash", "sh", "dash", "zsh", "ksh")
pythons = ("python3", "python")
# Bare interpreters in command position; the named interpreter variables
# anywhere; $BASH only in command position, since it is also passed as data;
# and any other shell-variable command given a -p or -I option cluster.
bare_interpreter = re.compile(
    lead + r"(?:/usr/bin/env[ \t]+)?(?:/(?:usr/)?bin/)?"
    r"(bash|sh|dash|zsh|ksh|python3|python|perl|node|ruby)(?=[ \t])", re.M
)
named_interpreter = re.compile(r'"?\$\{?(SG_BASH|PYTHON3_BIN|VALIDATOR_PY)\}?"?(?=[ \t])')
bash_variable = re.compile(lead + r'"?\$\{?(BASH)\}?"?(?=[ \t])', re.M)
flagged_variable = re.compile(
    r'"\$\{?([A-Za-z_][A-Za-z0-9_]*)\}?"'
    r"(?=[ \t]+-[BbcdEeIiOPpqSsuVvx]*[pI][BbcdEeIiOPpqSsuVvx]*[ \t])"
)
exec_call = re.compile(lead + r"exec[ \t]+(" + word + ")", re.M)
direct_script = re.compile(lead + r'("?\$[^\s"/]+/[^\s";|&)]*\.(?:sh|py)"?)', re.M)
option = re.compile(r"[ \t]+(--?[A-Za-z][A-Za-z-]*|--)(?=[ \t]|$)")
argument = re.compile(r"[ \t]+(" + word + ")")
redirect = re.compile(r"[0-9]*[<>]")
# A literal inline script must not load another file itself.
shell_loader = re.compile(
    r"(?:^|[\s;&|(`])(?:source|\.|eval|exec|bash|sh|dash|zsh|ksh|python3?|perl|node|ruby)(?=\s|$)"
    r"|\$\{?[0-9@*]"
)
python_loader = re.compile(
    r"(?<![\w.])(?:exec|execfile|eval|compile)\s*\(|\brunpy\b|\bimportlib\b|\bexec_module\b"
    r"|spec_from_file_location|\bsubprocess\b|\bos\s*\.\s*(?:system|popen|exec\w*|spawn\w*)"
    r"|\bsys\s*\.\s*path\b"
)
payload_like = re.compile(r"\$\{?(?:SKILL_DIR|_sg_lib_dir|_pg_\w+)\b|BASH_SOURCE|/scripts/|\.(?:sh|py)$")
seen = set()
errors = []


def unquote(raw):
    if len(raw) > 1 and raw[:1] in ('"', "'") and raw[-1:] == raw[:1]:
        return raw[1:-1]
    return raw


def check(path, number, raw, kind):
    target = unquote(raw)
    if kind == "interpreter" and target == "$WORK/approval.py":
        seen.add("generated-approval")
        return
    item = payload.get(target)
    if item is None:
        errors.append(f"{path}:{number}: unrecognized {kind} target {target}")
    elif item not in manifest:
        errors.append(f"{path}:{number}: {target} missing manifest entry {item}")
    else:
        seen.add(item)


def scan(line, stack):
    """Shell quoting over one physical line, continuing from stack.

    stack holds the open contexts: "code" (with its parenthesis depth), a
    double quote, or a single quote. A command substitution inside a double
    quote is code again, so "$(cmd <<'X'" starts a heredoc. Returns the line
    without comments and the heredocs it starts in code, as (delimiter, quoted).
    """
    out, docs, i = [], [], 0
    while i < len(line):
        ch, top = line[i], stack[-1]
        if top == "'":
            if ch == "'":
                stack.pop()
        elif ch == "\\":
            out.append(line[i:i + 2])
            i += 2
            continue
        elif line.startswith("$(", i):
            stack.append(["code", 0])
            out.append("$(")
            i += 2
            continue
        elif top == '"':
            if ch == '"':
                stack.pop()
        elif ch in "'\"":
            stack.append(ch)
        elif ch == "(":
            top[1] += 1
        elif ch == ")":
            if top[1]:
                top[1] -= 1
            elif len(stack) > 1:
                stack.pop()
        elif ch == "#" and (i == 0 or line[i - 1] in " \t;|&("):
            break
        elif line.startswith("<<", i) and not line.startswith("<<<", i) and line[i - 1:i] != "<":
            doc = re.match(
                r"<<-?[ \t]*(?:'([^']+)'|\"([^\"]+)\"|(\\)?([A-Za-z_][A-Za-z0-9_]*))", line[i:]
            )
            if doc:
                name = doc.group(1) or doc.group(2) or doc.group(4)
                docs.append((name, bool(doc.group(1) or doc.group(2) or doc.group(3))))
                out.append(doc.group(0))
                i += len(doc.group(0))
                continue
        out.append(ch)
        i += 1
    return "".join(out), docs


def words_after(line, pos):
    """The remaining arguments of this simple command, up to a redirection."""
    found = []
    while True:
        match = argument.match(line, pos)
        if not match or redirect.match(match.group(1)):
            return found
        found.append(match.group(1))
        pos = match.end()


def interpreter_call(path, number, line, end, family, docs, named):
    """Check one interpreter call whose options start at line[end:].

    Returns the language of a stdin heredoc script it reads, if any.
    """
    letters = ""
    while True:
        match = option.match(line, end)
        if not match:
            break
        end = match.end()
        if match.group(1) == "--":
            break
        if not match.group(1).startswith("--"):
            letters += match.group(1)[1:]
    match = argument.match(line, end)
    if not match or redirect.match(match.group(1)):
        if not named:
            errors.append(f"{path}:{number}: unrecognized interpreter call without a script file")
        return None
    raw = match.group(1)
    rest = words_after(line, match.end())
    inline = "e" if family == "other" else "c"
    if inline in letters:
        literal = raw.startswith("'") or (raw.startswith('"') and not re.search(r"[$`\\]", raw))
        loaders = {"shell": (shell_loader,), "python": (python_loader,)}.get(
            family, (shell_loader, python_loader))
        if not literal or any(rx.search(unquote(raw)) for rx in loaders):
            errors.append(f"{path}:{number}: unrecognized inline script {raw}")
        for item in rest:
            if not re.fullmatch(r"[A-Za-z0-9_-]+", item):
                check(path, number, item, "inline script argument")
        return None
    if unquote(raw) == "-" or (family == "shell" and "s" in letters):
        if len(docs) != 1 or not docs[0][1]:
            errors.append(f"{path}:{number}: unrecognized stdin script without one quoted heredoc")
        for item in rest:
            if payload_like.search(unquote(item)):
                check(path, number, item, "stdin script argument")
        return "shell" if family == "shell" else "python"
    # A named variable outside command position is often data ([ -n "$X" ]);
    # only a script-shaped word after it is a call target.
    if not named or letters or re.match(r'''"\$|/|\$[A-Za-z_]|[A-Za-z0-9_.-]+\.(?:sh|py)\b''', raw):
        check(path, number, raw, "interpreter")
    return None


def inventory(path, number, text, docs):
    """Check every call in one logical line; return a stdin heredoc's language."""
    if eval_call.search(text):
        errors.append(f"{path}:{number}: unrecognized eval")
    for found in source_call.finditer(text):
        check(path, number, found.group(1), "source")
    calls = []
    for found in bare_interpreter.finditer(text):
        name = found.group(1)
        family = "shell" if name in shells else "python" if name in pythons else "other"
        calls.append((found.end(), family, False))
    for found in named_interpreter.finditer(text):
        calls.append((found.end(), "shell" if found.group(1) == "SG_BASH" else "python", True))
    for found in bash_variable.finditer(text):
        calls.append((found.end(), "shell", False))
    for found in flagged_variable.finditer(text):
        if found.group(1) not in ("SG_BASH", "PYTHON3_BIN", "VALIDATOR_PY"):
            calls.append((found.end(), "unknown", False))
    body = None
    for end, family, named in calls:
        body = interpreter_call(path, number, text, end, family, docs, named) or body
    for found in exec_call.finditer(text):
        target = unquote(found.group(1))
        if target.rsplit("/", 1)[-1] in shells + pythons + ("perl", "node", "ruby", "env") \
                or re.fullmatch(r"\$\{?(?:SG_BASH|PYTHON3_BIN|VALIDATOR_PY|BASH)\}?", target):
            continue
        check(path, number, found.group(1), "exec")
    for found in direct_script.finditer(text):
        check(path, number, found.group(1), "exec")
    return body


for path in (adapter, diff, osv, engine, common, diff_base):
    heredoc = None
    stack = [["code", 0]]
    logical = ""
    first_line = 0
    for number, line in enumerate(path.read_text().splitlines(), 1):
        if heredoc:
            name, body = heredoc
            if line.strip() == name:
                heredoc = None
                continue
            if body == "python" and python_loader.search(line):
                errors.append(f"{path}:{number}: unrecognized file load in a stdin script")
            if body != "shell":
                continue
        if not logical:
            first_line = number
        piece, docs = scan(line, stack)
        if docs:
            # The heredoc body starts on the next line, even inside "$(".
            body = inventory(path, first_line, logical + piece, docs)
            heredoc, logical = (docs[-1][0], body), ""
        elif stack[-1] != "'" and piece.rstrip().endswith("\\"):
            logical += piece.rstrip()[:-1] + " "
        elif len(stack) > 1:
            logical += piece + "\n"
        else:
            inventory(path, first_line, logical + piece, docs)
            logical = ""
    if heredoc or len(stack) > 1:
        errors.append(f"{path}: unrecognized unterminated heredoc or quote from line {first_line}")

# The generated Python file is not a payload, but must remain literal content
# in the gate's private mktemp directory rather than a checkout-provided file.
diff_text = diff.read_text()
if "generated-approval" in seen and (
    'WORK="$(mktemp -d)"' not in diff_text
    or 'cat > "$WORK/approval.py" <<\'PY\'' not in diff_text
):
    errors.append("generated approval.py is not a literal in the private work directory")

expected = {"gate", "security-engine", "security-osv", "security-baseline",
            "process-common", "process-common-diff-base", "security-diff-base"}
for item in sorted(expected - seen):
    errors.append(f"payload inventory: no observed call for {item}")
if errors:
    sys.exit("\n".join(errors))
print("payload inventory: all observed source and interpreter files are covered")
