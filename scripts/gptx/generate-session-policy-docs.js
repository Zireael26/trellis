#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');
const {
  POLICY_VERSION,
  MODES,
  ADVISOR_INPUTS,
  DELEGATE_INPUTS,
  MODEL_INPUT_CLASSES,
  MODE_DEFAULTS,
  MODEL_CLASS_EXAMPLES,
  resolveModelAlias,
  classifyModel,
  resolveLaunch,
} = require('./session-policy');

const OMITTED = '(omitted)';
const display = (value) => value == null ? OMITTED : String(value);
const cell = (value) => display(value).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const yesNo = (value) => value ? 'yes' : 'no';

const modeRows = () => {
  const rows = [];
  const advisorCases = [null, ...ADVISOR_INPUTS];
  const delegateCases = [null, ...DELEGATE_INPUTS];
  for (const mode of MODES) {
    for (const advisor of advisorCases) {
      for (const delegates of delegateCases) {
        const resolved = resolveLaunch({ mode, advisor, delegates });
        if (!resolved.valid) throw new Error(`unexpected invalid policy row: ${resolved.error}`);
        rows.push({ resolved, advisor, delegates });
      }
    }
  }
  if (rows.length !== 120) throw new Error(`mode matrix expected 120 rows, got ${rows.length}`);
  return rows;
};

const modelRows = () => {
  const rows = [];
  for (const mode of MODES) {
    for (const modelClass of MODEL_INPUT_CLASSES) {
      const model = MODEL_CLASS_EXAMPLES[modelClass];
      const resolved = resolveLaunch({ mode, model });
      const requestedModel = model == null ? MODE_DEFAULTS[mode].model : model;
      const effectiveModel = resolveModelAlias(requestedModel);
      const classification = classifyModel(effectiveModel);
      rows.push({ mode, modelClass, model, resolved, effectiveModel, classification });
    }
  }
  if (rows.length !== 24) throw new Error(`model matrix expected 24 rows, got ${rows.length}`);
  return rows;
};

const renderModeMatrix = () => {
  const rows = modeRows();
  const lines = [
    '# GPTX session policy matrix',
    '',
    '<!-- GENERATED by scripts/gptx/generate-session-policy-docs.js; do not edit the table manually. -->',
    '',
    `Policy version: ${POLICY_VERSION}. Generated rows: ${rows.length}.`,
    '',
    'This is the complete Cartesian product of four modes, six advisor inputs, and five delegate inputs. Agent provider locks apply after each child model slot is resolved through the launcher-captured alias map; policy permission does not promise provider quota or topology capability.',
    '',
    '| Mode | Main / topology | Advisor input | Effective advisor | Advisor source | Delegates input | Effective delegates | Delegate source | Agent usable | Allowed known providers | Capability note | Validation |',
    '|---|---|---|---|---|---|---|---|---:|---|---|---|',
  ];
  for (const { resolved, advisor, delegates } of rows) {
    const effective = resolved.effective;
    lines.push(`| ${[
      effective.mode,
      `${effective.main_model} / ${effective.topology}`,
      display(advisor),
      effective.advisor,
      effective.advisor_source,
      display(delegates),
      effective.delegates,
      effective.delegates_source,
      yesNo(effective.agent_usable),
      effective.allowed_agent_providers.join(', ') || 'none',
      effective.capability_note,
      'valid',
    ].map(cell).join(' | ')} |`);
  }
  lines.push('');
  return `${lines.join('\n')}\n`;
};

const renderModelMatrix = () => {
  const rows = modelRows();
  const lines = [
    '# GPTX model override matrix',
    '',
    '<!-- GENERATED by scripts/gptx/generate-session-policy-docs.js; do not edit the table manually. -->',
    '',
    `Policy version: ${POLICY_VERSION}. Generated rows: ${rows.length}.`,
    '',
    'This is the complete Cartesian product of four modes and six semantic main-model input classes. The example model represents its whole family. Agent model slots are a separate pre-spawn contract: the guard resolves launcher-captured aliases before provider classification and never remaps provider-stable full IDs.',
    '',
    '| Mode | Model class | Model input | Effective main | Provider | Classification source | Valid | Topology | Terra advisor recommended | Validation |',
    '|---|---|---|---|---|---|---:|---|---:|---|',
  ];
  for (const row of rows) {
    const effective = row.resolved.effective;
    lines.push(`| ${[
      row.mode,
      row.modelClass,
      display(row.model),
      row.effectiveModel,
      row.classification.provider,
      row.model == null ? 'mode-default' : 'explicit-model',
      yesNo(row.resolved.valid),
      effective?.topology || 'n/a',
      yesNo(row.classification.family === 'terra'),
      row.resolved.valid ? 'valid' : row.resolved.error,
    ].map(cell).join(' | ')} |`);
  }
  lines.push('');
  return `${lines.join('\n')}\n`;
};

const generatedDocs = () => ({
  'gptx-session-policy-matrix.md': renderModeMatrix(),
  'gptx-model-override-matrix.md': renderModelMatrix(),
});

const parseArgs = (argv) => {
  const args = { outputDir: path.resolve(__dirname, '../..', 'docs') };
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === '--output-dir') args.outputDir = path.resolve(argv[++index]);
    else if (arg.startsWith('--output-dir=')) args.outputDir = path.resolve(arg.slice('--output-dir='.length));
    else throw new Error(`unknown argument: ${arg}`);
  }
  return args;
};

const main = () => {
  try {
    const args = parseArgs(process.argv.slice(2));
    const docs = generatedDocs();
    fs.mkdirSync(args.outputDir, { recursive: true });
    for (const [filename, content] of Object.entries(docs)) {
      fs.writeFileSync(path.join(args.outputDir, filename), content);
    }
    process.stdout.write(`generated mode rows=120 model rows=24 in ${args.outputDir}\n`);
  } catch (error) {
    process.stderr.write(`generate-session-policy-docs: ${error.message}\n`);
    process.exitCode = 1;
  }
};

if (require.main === module) main();

module.exports = {
  modeRows,
  modelRows,
  renderModeMatrix,
  renderModelMatrix,
  generatedDocs,
  parseArgs,
};
